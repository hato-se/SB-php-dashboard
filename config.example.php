<?php

// ============================================================
// SwitchBot ダッシュボード — 設定ファイルテンプレート
//
// 使い方:
//   1. このファイルを config.php という名前でコピーする
//   2. 下記の各値を自分の環境に合わせて書き換える
//   3. FTP でサーバーにアップロードする（config.php のみ）
//
// ※ config.php はサーバー上で .htaccess により外部から直接
//    アクセスできないよう保護されています。
// ============================================================

// ----------------------------------------------------------
// SwitchBot 認証情報
// SwitchBot アプリ → プロフィール → 設定 → アプリについて を開き
// バージョン番号を10回タップ → デベロッパーオプション → トークン取得
// で Open Token と Secret Key を確認できます。
// ----------------------------------------------------------
define('SWITCHBOT_TOKEN',  'your_open_token_here');
define('SWITCHBOT_SECRET', 'your_secret_key_here');

// ----------------------------------------------------------
// キャッシュ設定
// API レスポンスをサーバー上にキャッシュする秒数。
// 0 を指定するとキャッシュを使用しません。
// ----------------------------------------------------------
define('CACHE_TTL', 60);

// ----------------------------------------------------------
// キャッシュ保存ディレクトリ
// 書き込み権限（755 または 777）が必要です。
// レンタルサーバーの場合は FTP クライアントでパーミッションを変更してください。
// ----------------------------------------------------------
define('CACHE_DIR', __DIR__ . '/cache');

// ----------------------------------------------------------
// タイムゾーン
// ----------------------------------------------------------
define('TIMEZONE', 'Asia/Tokyo');

// ----------------------------------------------------------
// デバッグモード
// 本番環境では false にしてください。
// ----------------------------------------------------------
define('DEBUG_MODE', false);
